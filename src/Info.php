    public static function boot(): void
    {
        if (self::$liveStates !== []) {
            return;
        }
        self::$liveStates = self::STATES;
        self::$liveMobjinfo = self::MOBJINFO;
        foreach (self::$liveMobjinfo as $i => $row) {
            if ((int) $row[0] !== -1) {
                self::$doomed[(int) $row[0]] = $i;
            }
        }
    }

    public static function mobjTypeForDoomednum(int $doomednum): int
    {
        self::boot();
        return self::$doomed[$doomednum] ?? -1;
